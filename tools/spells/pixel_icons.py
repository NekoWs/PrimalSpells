DIGITS = {'1': ('..I', '.II', '..I', '..I', '..I'),
          '2': ('III', '..I', 'III', 'I..', 'III'),
          '3': ('III', '..I', '.II', '..I', 'III'),
          '5': ('III', 'I..', 'III', '..I', 'III'),
          '0': ('III', 'I.I', 'I.I', 'I.I', 'III')}
for _name, _number in (('divide_two', '2'), ('divide_three', '3'), ('divide_five', '5'), ('divide_ten', '10')):
    _image = Image.new('RGBA', (12, 12))
    _draw = ImageDraw.Draw(_image)
    # 原卡与右下方的副本同形；数字只标复制份数，不混入施法轨迹。
    for _x, _y in ((1, 0), (3, 2)):
        _draw.rectangle((_x, _y, _x + 5, _y + 7), fill=PALETTE['P'])
        _draw.rectangle((_x + 1, _y + 1, _x + 4, _y + 6), fill=PALETTE['L'])
        _draw.line((_x + 1, _y + 1, _x + 1, _y + 5), fill=PALETTE['W'])
    _left = 12 - (len(_number) * 4 - 1)
    _draw.rectangle((_left - 1, 6, 11, 11), fill=PALETTE['K'])
    for _i, _digit in enumerate(_number):
        for _y, _row in enumerate(DIGITS[_digit]):
            for _x, _c in enumerate(_row):
                if _c == 'I':
                    _image.putpixel((_left + _i * 4 + _x, _y + 7), (200, 245, 244, 255))
    record_image(_name, _image)

