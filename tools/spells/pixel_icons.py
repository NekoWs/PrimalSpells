def card_fan(name, count):
    """多链施放：每张卡保留分开的顶边；全量额外带抽尽牌堆的箭头。"""
    image = Image.new('RGBA', (12, 12))
    draw = ImageDraw.Draw(image)
    step = 2
    left = (12 - (count - 1) * step - 4) // 2
    for i in range(count):
        x, y = left + i * step, 1 + abs(i - count // 2)
        draw.rectangle((x, y, x + 3, min(y + 7, 10)), fill=CARD_COLORS['D'])
        draw.line((x + 1, y + 1, x + 2, y + 1), fill=CARD_COLORS['W'])
        draw.line((x + 1, y + 2, x + 1, min(y + 6, 9)), fill=CARD_COLORS['P'])
    if name == 'cast_all':
        draw.line(((1, 11), (10, 11), (8, 9)), fill=CARD_COLORS['W'])
    record_image(name, image)


def record_image(name, image):
    """将小型同族构图保存为与手绘稿相同的12×12字符表，不放大或采样。"""
    colors = sorted({image.getpixel((x, y)) for y in range(12) for x in range(12)} - {(0, 0, 0, 0)})
    keys = {color: chr(65 + i) for i, color in enumerate(colors)}
    palette = {keys[color]: '#%02x%02x%02x' % color[:3] for color in colors}
    rows = tuple(''.join(keys.get(image.getpixel((x, y)), '.') for x in range(12)) for y in range(12))
    SPRITES[name] = (palette, rows)


